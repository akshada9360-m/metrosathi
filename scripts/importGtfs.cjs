// scripts/importGtfs.cjs
// Reads GTFS files and generates scheduled bus data for Metro Saathi.
// This script does NOT modify the UI or invent metro-exit mappings.

const fs = require('node:fs')
const path = require('node:path')

const GTFS_DIR = path.join(
  process.env.TEMP || '',
  'pmpml_gtfs_original',
)

const OUTPUT_FILE = path.join(
  process.cwd(),
  'src',
  'data',
  'gtfsScheduled.ts',
)

const REQUIRED_FILES = [
  'routes.txt',
  'trips.txt',
  'stops.txt',
  'stop_times.txt',
  'calendar.txt',
]

function readCsv(filename) {
  const filePath = path.join(GTFS_DIR, filename)

  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing GTFS file: ${filePath}`)
  }

  const text = fs.readFileSync(filePath, 'utf8').replace(/^\uFEFF/, '')
  const lines = text.split(/\r?\n/).filter(Boolean)

  function parseLine(line) {
    const fields = []
    let field = ''
    let insideQuotes = false

    for (let i = 0; i < line.length; i++) {
      const char = line[i]

      if (char === '"') {
        if (insideQuotes && line[i + 1] === '"') {
          field += '"'
          i++
        } else {
          insideQuotes = !insideQuotes
        }
      } else if (char === ',' && !insideQuotes) {
        fields.push(field)
        field = ''
      } else {
        field += char
      }
    }

    fields.push(field)
    return fields
  }

  const headers = parseLine(lines[0])

  return lines.slice(1).map((line) => {
    const values = parseLine(line)
    return Object.fromEntries(
      headers.map((header, index) => [header, values[index] ?? '']),
    )
  })
}

function isServiceActive(service, today) {
  if (!service) return false

  const dateText = today.toISOString().slice(0, 10).replaceAll('-', '')
  if (dateText < service.start_date || dateText > service.end_date) {
    return false
  }

  const dayFields = [
    'sunday',
    'monday',
    'tuesday',
    'wednesday',
    'thursday',
    'friday',
    'saturday',
  ]

  const weekday = today.getDay()
  return service[dayFields[weekday]] === '1'
}

function formatTime(time) {
  // Keep HH:MM for Metro Saathi's current departure-time format.
  const parts = time.split(':')
  if (parts.length < 2) return time
  return `${parts[0].padStart(2, '0')}:${parts[1].padStart(2, '0')}`
}

for (const filename of REQUIRED_FILES) {
  if (!fs.existsSync(path.join(GTFS_DIR, filename))) {
    throw new Error(
      `Cannot find ${filename}. Expected GTFS files in: ${GTFS_DIR}`,
    )
  }
}

console.log('Reading GTFS files...')

const routes = readCsv('routes.txt')
const trips = readCsv('trips.txt')
const stops = readCsv('stops.txt')
const stopTimes = readCsv('stop_times.txt')
const calendar = readCsv('calendar.txt')

const today = new Date()
const activeServiceIds = new Set(
  calendar
    .filter((service) => isServiceActive(service, today))
    .map((service) => service.service_id),
)

// Find GTFS stops whose names identify them as Civil Court Metro Station.
const stationStops = stops.filter((stop) =>
  /civil court metro station/i.test(stop.stop_name),
)

if (stationStops.length === 0) {
  throw new Error(
    'No stop matching "Civil Court Metro Station" was found in stops.txt.',
  )
}

const stationStopIds = new Set(stationStops.map((stop) => stop.stop_id))
const routeById = new Map(routes.map((route) => [route.route_id, route]))
const tripsById = new Map(trips.map((trip) => [trip.trip_id, trip]))

const relevantTrips = trips.filter(
  (trip) =>
    activeServiceIds.has(trip.service_id) &&
    stopTimes.some(
      (stopTime) =>
        stopTime.trip_id === trip.trip_id &&
        stationStopIds.has(stopTime.stop_id),
    ),
)

const outputRecords = relevantTrips.flatMap((trip) => {
  const route = routeById.get(trip.route_id)
  if (!route) return []

  const matchingTimes = stopTimes
    .filter(
      (stopTime) =>
        stopTime.trip_id === trip.trip_id &&
        stationStopIds.has(stopTime.stop_id),
    )
    .map((stopTime) => {
      const stop = stationStops.find(
        (candidate) => candidate.stop_id === stopTime.stop_id,
      )

      return {
        routeId: trip.route_id,
        routeNumber: route.route_short_name,
        routeName: route.route_long_name,
        tripId: trip.trip_id,
        serviceId: trip.service_id,
        stopId: stopTime.stop_id,
        stopName: stop?.stop_name ?? 'Unknown stop',
        scheduledTime: formatTime(stopTime.departure_time),
        dataType: 'scheduled',
        source: 'Community-generated PMPML GTFS feed',
      }
    })

  return matchingTimes
})

outputRecords.sort((a, b) =>
  a.scheduledTime.localeCompare(b.scheduledTime),
)

const output = `// Generated by scripts/importGtfs.cjs — do not edit manually.
// These are scheduled feed times, NOT live arrival predictions.
// The GTFS stop-to-metro-exit walking relationship is not verified.

export interface GtfsScheduledStopTime {
  routeId: string
  routeNumber: string
  routeName: string
  tripId: string
  serviceId: string
  stopId: string
  stopName: string
  scheduledTime: string
  dataType: 'scheduled'
  source: string
}

export const gtfsScheduledStopTimes: GtfsScheduledStopTime[] = ${JSON.stringify(
  outputRecords,
  null,
  2,
)}
`

fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true })
fs.writeFileSync(OUTPUT_FILE, output, 'utf8')

console.log(`Found ${stationStops.length} matching Civil Court stop(s).`)
console.log(`Generated ${outputRecords.length} scheduled stop-time record(s).`)
console.log(`Output: ${OUTPUT_FILE}`)
console.log('Reminder: scheduled data only; not live arrivals.')